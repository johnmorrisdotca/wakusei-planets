import "./load.ts";
import { expect, test, type Page } from "@playwright/test";
import { callOn, NOV2, openSpace, SPACE } from "./space-ui.ts";

const BASE = "/wakusei-planets/";
const filter = (page: Page, category: string, value: string) => page.locator(`#moon-filters [data-moon-filter="${category}"][data-moon-value="${value}"]`);
const noSideways = (page: Page) => page.evaluate(() => document.documentElement.scrollWidth - document.documentElement.clientWidth);

test("space filters load on demand and update the Jupiter list, dots and detail card", async ({ page, browserName }) => {
  test.skip(browserName !== "chromium", "space WebGL uses Chromium's software renderer");
  const catalogueRequests: string[] = [];
  page.on("request", (request) => {
    if (/\/moon-catalogue-\w+\.js/.test(request.url())) catalogueRequests.push(request.url());
  });
  await openSpace(page, `t=${NOV2}&play=off&goto=jupiter-moons&moonsize=4`);
  const space = page.locator(SPACE);
  const dots = () => space.evaluate((el) => (Reflect.get(el, "stats") as { allMoons: { dots: number } }).allMoons.dots);
  expect(catalogueRequests).toEqual([]);
  await callOn(page, "goTo", "jupiter", { smooth: false });
  await expect.poll(() => space.evaluate((el) => Reflect.get(el, "body"))).toBe("jupiter");
  await page.locator("#all-moons").click();
  await expect(page.locator("#moon-rows tr")).toHaveCount(115);
  expect(catalogueRequests.length).toBeGreaterThan(0);
  await filter(page, "status", "provisional").click();
  await expect(page.locator("#moon-rows tr")).toHaveCount(42);
  await filter(page, "status", "").click();
  await filter(page, "size", "measured").click();
  await expect(page.locator("#moon-rows tr")).toHaveCount(3);
  await filter(page, "size", "").click();
  await filter(page, "direction", "retrograde").click();
  await expect(page.locator("#moon-rows tr")).toHaveCount(92);
  await filter(page, "direction", "").click();
  await page.locator("#moon-filters summary").click();
  await page.getByLabel("Orbit group").selectOption("himalia");
  await expect(page.locator("#moon-rows tr")).toHaveCount(11);
  await expect(page.locator("#moon-key")).toHaveText("Himalia group 11");
  await page.getByRole("button", { name: "Himalia", exact: true }).click();
  await expect(page.locator("#moon-card")).toBeVisible();
  await expect(page.locator("#moon-card h3")).toHaveText("Himalia");
  await expect(page.locator("#moon-card")).toContainText("1904");
  await expect(page.locator("#moon-card")).toContainText("Position accuracy");
  await expect(page.locator("#moon-card dd").filter({ hasText: "JUP347" })).toHaveCount(0);
  await expect(page.locator("#moon-card").getByRole("link", { name: "Mean elements (JUP347)" })).toBeVisible();
  await space.scrollIntoViewIfNeeded();
  await expect.poll(dots).toBe(11);
  expect(await space.evaluate((el) => Reflect.get(el, "moonSize"))).toBe(4);
  expect(await noSideways(page)).toBeLessThanOrEqual(0);
});

test("the planet line view filters small moons, plays discovery years and opens a card", async ({ page }, testInfo) => {
  await page.emulateMedia({ reducedMotion: "no-preference" });
  const requests: string[] = [];
  page.on("request", (request) => {
    if (/\/body-moons-\w+\.js/.test(request.url())) requests.push(request.url());
  });
  await page.goto(`${BASE}?body=jupiter&look=line&moons=1&t=${NOV2}&play=off`);
  const main = page.locator("#main");
  await expect(main.locator("#stage > svg")).toBeVisible();
  expect(requests).toEqual([]);
  await page.locator("#moon-all").click();
  const dots = main.locator("[data-moon-dot]");
  await expect(dots).toHaveCount(109);
  expect(requests.length).toBeGreaterThan(0);
  await page.locator("#moon-orbits").click();
  await expect(main).toHaveAttribute("moon-orbits", "off");
  await page.locator("#moon-filters summary").click();
  await page.getByLabel("Orbit group").selectOption("himalia");
  await expect(dots).toHaveCount(11);
  await filter(page, "status", "provisional").click();
  await expect(dots).toHaveCount(4);
  await filter(page, "status", "").click();
  await page.locator("#moon-pick select").selectOption("himalia");
  await expect(page.locator("#moon-card h3")).toHaveText("Himalia");
  await page.getByRole("button", { name: "Close moon details" }).click();
  await main.evaluate((el) => Reflect.set(el, "moonFilter", { group: "himalia", discovered: { from: 1904, to: 1904 } }));
  await expect(dots).toHaveCount(1);
  if (testInfo.project.use.hasTouch) await dots.tap({ force: true });
  else await dots.click({ force: true });
  await expect(page.locator("#moon-card h3")).toHaveText("Himalia");
  await expect(page.locator("#moon-card")).toBeVisible();
  const seenAt = await dots.getAttribute("cx");
  await main.evaluate((el) => el.setAttribute("rate", "86400"));
  await expect.poll(() => dots.getAttribute("cx")).not.toBe(seenAt);
  await main.evaluate((el) => el.setAttribute("rate", "0"));
  await main.evaluate((el) => Reflect.set(el, "moonFilter", { group: "himalia" }));
  await page.getByLabel("Orbit group").selectOption("");
  const play = page.getByRole("button", { name: "Play discoveries" });
  await play.click();
  const pause = page.getByRole("button", { name: "Pause discoveries" });
  await expect(pause).toBeVisible();
  await expect(page.locator("[data-moon-year=from]")).toHaveValue("1610");
  await expect(dots).toHaveCount(0);
  await pause.click();
  const year = await page.locator("[data-moon-year=to]").inputValue();
  await expect(play).toBeVisible();
  await expect(page.locator("[data-moon-year=to]")).toHaveValue(year);
  await page.getByRole("button", { name: "Clear years" }).click();
  await expect(dots).toHaveCount(109);
  expect(await noSideways(page)).toBeLessThanOrEqual(0);
});

test("the code builder passes the moon filters to both the code and embed frame", async ({ page }) => {
  await page.goto(`${BASE}builder.html`);
  await expect(page.locator("html")).toHaveAttribute("data-ready", "true");
  await page.getByTestId("body-jupiter").click();
  await page.getByTestId("moon-mode-all").click();
  await filter(page, "size", "measured").click();
  await page.locator("#builder-moon-orbits").click();
  const panel = page.locator("#embed-panel");
  const code = panel.locator('[part="code"]');
  await expect(code).toContainText('moons="all"');
  await expect(code).toContainText('moon-size-class="measured"');
  await expect(code).toContainText('moon-orbits="off"');
  const preview = panel.locator('[part="preview"] wakusei-body');
  await expect(preview.locator("[data-moon-dot]")).toHaveCount(3);
  const address = await panel.locator('[part="open"]').getAttribute("href");
  await page.goto(`${BASE}${address!}`);
  await expect(page.locator("wakusei-body")).toHaveAttribute("moon-size-class", "measured");
  await expect(page.locator("wakusei-body [data-moon-dot]")).toHaveCount(3);
});
